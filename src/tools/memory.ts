// Shared memory: a git repo of markdown on hub ("brain").
import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { execFile } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, appendFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { promisify } from 'node:util';
import { z } from 'zod';
import { findProject, projectDir, UserError, type Machine } from '../config.ts';
import { q, qpath, runOk } from '../transport/ssh.ts';
import { tool, type Ctx } from './common.ts';

const exec = promisify(execFile);
const MAX_FILE = 20_000, MAX_CONTEXT = 100_000;

export const brainDir = () => resolve((process.env.BRAIN_DIR ?? '~/brain').replace(/^~(?=$|\/)/, homedir()));
/** Where the brain lives on the other machines (synced there by git or Syncthing). */
const REMOTE_BRAIN = process.env.REMOTE_BRAIN_DIR ?? '~/brain';

export async function ensureBrain(dir = brainDir()) {
  for (const d of ['shared', 'projects', 'skills']) mkdirSync(join(dir, d), { recursive: true });
  if (!existsSync(join(dir, 'index.md'))) writeFileSync(join(dir, 'index.md'), '# Brain index\n\nProjects, tags and how they relate.\n');
  // context.md is generated and copied to each machine at session start; syncing it would only conflict.
  if (!existsSync(join(dir, '.gitignore'))) writeFileSync(join(dir, '.gitignore'), 'projects/*/context.md\n');
  if (!existsSync(join(dir, '.git'))) {
    await git(dir, 'init', '-q');
    await commit(dir, 'init brain');
  }
}

/** Resolve a brain-relative path, refusing anything outside the repo or inside .git. */
export function brainPath(rel: string, dir = brainDir()): string {
  const p = resolve(dir, rel.replace(/^\/+/, ''));
  if (p !== dir && !p.startsWith(dir + sep)) throw new UserError(`Path ${rel} is outside the brain.`);
  if (relative(dir, p).split(sep).includes('.git')) throw new UserError('The .git folder is off limits.');
  return p;
}

const git = (dir: string, ...args: string[]) =>
  exec('git', ['-C', dir, '-c', 'user.name=session-orchestrator', '-c', 'user.email=orchestrator@localhost', ...args]);

// One git operation at a time, or concurrent writes trip over index.lock.
let queue: Promise<unknown> = Promise.resolve();
export function commit(dir: string, message: string): Promise<void> {
  const next = queue.then(async () => {
    await git(dir, 'add', '-A');
    const { stdout } = await git(dir, 'status', '--porcelain');
    if (!stdout.trim()) return;
    await git(dir, 'commit', '-q', '-m', message);
    if (process.env.BRAIN_PUSH === '1') git(dir, 'push', '-q').catch((e) => console.error('brain push failed:', e.message));
  });
  queue = next.catch(() => {});
  return next;
}

/** Shared paths linked to a project: projects.yaml `shared` + lines in projects/<p>/links.md. */
export function links(ctx: Ctx, pid: string, dir = brainDir()): string[] {
  const p = findProject(ctx.cfg, pid);
  const f = join(dir, 'projects', p.id, 'links.md');
  const extra = existsSync(f)
    ? readFileSync(f, 'utf8').split('\n').map((l) => l.match(/^- (\S+)/)?.[1]).filter((x): x is string => !!x)
    : [];
  return [...new Set([...p.shared, ...extra])];
}

function mdFiles(p: string): string[] {
  if (!existsSync(p)) return [];
  if (statSync(p).isFile()) return [p];
  return readdirSync(p, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile() && /\.(md|txt|ya?ml)$/.test(e.name) && !join(e.parentPath, e.name).includes(`${sep}.git${sep}`))
    .map((e) => join(e.parentPath, e.name)).sort();
}

/** Project notes + linked shared files + related skills, as one markdown document. */
export function projectContext(ctx: Ctx, pid: string, dir = brainDir()) {
  const p = findProject(ctx.cfg, pid);
  const skip = new Set(['context.md', 'log.md', 'links.md']);
  const notes = mdFiles(join(dir, 'projects', p.id)).filter((f) => !skip.has(relative(join(dir, 'projects', p.id), f)));
  const linked = links(ctx, p.id, dir);
  const shared = linked.flatMap((l) => mdFiles(brainPath(l, dir)));
  const skills = existsSync(join(dir, 'skills'))
    ? readdirSync(join(dir, 'skills'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name)
    : [];
  const related = skills.filter((s) => linked.some((l) => l === `skills/${s}` || l.startsWith(`skills/${s}/`)));
  const section = (f: string) => {
    const body = readFileSync(f, 'utf8');
    return `### ${relative(dir, f)}\n\n${body.length > MAX_FILE ? body.slice(0, MAX_FILE) + '\n… (truncated)' : body.trim()}\n`;
  };
  let md = `# Context for ${p.id}\n\n_Generated by session-orchestrator. Do not edit; edit the brain files instead._\n\n` +
    `## Project notes\n\n${notes.map(section).join('\n') || '(none yet)\n'}\n` +
    `## Shared knowledge\n\n${shared.map(section).join('\n') || '(nothing linked)\n'}\n` +
    `## Skills\n\nRelated: ${related.join(', ') || 'none'}. All shared skills: ${skills.join(', ') || 'none'}.\n`;
  if (md.length > MAX_CONTEXT) md = md.slice(0, MAX_CONTEXT) + '\n… (context truncated)\n';
  return { markdown: md, notes: notes.map((f) => relative(dir, f)), shared: shared.map((f) => relative(dir, f)), related_skills: related };
}

/**
 * Before a session starts: regenerate context.md, make sure the target machine has it,
 * and make sure the project's CLAUDE.md imports it.
 */
export async function injectContext(ctx: Ctx, m: Machine, pid: string, dir = brainDir()) {
  const p = findProject(ctx.cfg, pid);
  const rel = `projects/${p.id}/context.md`;
  const local = join(dir, rel);
  mkdirSync(dirname(local), { recursive: true });
  const { markdown } = projectContext(ctx, p.id, dir);
  writeFileSync(local, markdown);
  let importPath = local;
  if (!m.local) {
    // Copy directly so the session never starts on a stale file, whatever the sync method.
    const remote = `${REMOTE_BRAIN}/${rel}`;
    await runOk(m, `mkdir -p ${qpath(dirname(remote))} && cat > ${qpath(remote)}`, 8000, markdown);
    importPath = remote;
  }
  const line = `@${importPath}`;
  const claudeMd = `${projectDir(m, p)}/CLAUDE.md`;
  await runOk(m, `grep -qxF ${q(line)} ${qpath(claudeMd)} 2>/dev/null || printf '\\n%s\\n' ${q(line)} >> ${qpath(claudeMd)}`);
}

/** Append a "what happened in this session" entry to projects/<p>/log.md. */
export async function logSession(ctx: Ctx, pid: string, session: string, text: string, dir = brainDir()) {
  let p;
  try { p = findProject(ctx.cfg, pid); } catch { return; } // adopted session of an unknown project
  const f = join(dir, 'projects', p.id, 'log.md');
  mkdirSync(dirname(f), { recursive: true });
  if (!existsSync(f)) writeFileSync(f, `# ${p.id} session log\n`);
  appendFileSync(f, `\n## ${new Date().toISOString().slice(0, 16).replace('T', ' ')} · ${session}\n\n${text.trim()}\n`);
  await commit(dir, `log: ${session}`);
}

async function search(dir: string, query: string, scope: string) {
  const base = brainPath(scope, dir);
  const run = async (bin: string, args: string[]) => {
    try { return (await exec(bin, args, { maxBuffer: 4 << 20 })).stdout; }
    catch (e) { const x = e as { code?: number | string; stdout?: string }; if (x.code === 1) return ''; throw e; }
  };
  let out: string;
  try {
    out = await run('rg', ['-n', '-i', '-F', '--max-count', '3', '--glob', '!.git', '--', query, base]);
  } catch (e) {
    if ((e as { code?: string }).code !== 'ENOENT') throw e;
    // shortcut: grep fallback when ripgrep is not installed; same results, slower on a big brain.
    out = await run('grep', ['-rniIF', '-m', '3', '--exclude-dir=.git', '--', query, base]);
  }
  return out.split('\n').filter(Boolean).slice(0, 50).map((l) => {
    const m = l.match(/^(.*?):(\d+):(.*)$/);
    return m ? { path: relative(dir, m[1]), line: +m[2], text: m[3].trim().slice(0, 200) } : { path: '', line: 0, text: l };
  });
}

export function register(server: McpServer, ctx: Ctx) {
  const dir = brainDir();

  tool(server, ctx, 'memory_search', 'Search the shared brain (notes, shared knowledge, skills). scope narrows it, e.g. "shared/deployment" or "projects/myapp".',
    { query: z.string().min(1), scope: z.string().default('.') },
    async ({ query, scope }) => {
      const hits = await search(dir, query, scope);
      const files = [...new Set(hits.map((h) => h.path))];
      return {
        summary: hits.length ? `${hits.length} matches in ${files.length} files: ${files.slice(0, 5).join(', ')}.` : `Nothing found for "${query}".`,
        hits,
      };
    });

  tool(server, ctx, 'memory_read', 'Read a brain file, or list a brain folder.',
    { path: z.string() },
    async ({ path }) => {
      const p = brainPath(path, dir);
      if (!existsSync(p)) throw new UserError(`${path} does not exist in the brain.`);
      if (statSync(p).isDirectory()) {
        const entries = readdirSync(p, { withFileTypes: true }).filter((e) => e.name !== '.git').map((e) => e.name + (e.isDirectory() ? '/' : ''));
        return { summary: `${path} has ${entries.length} entries.`, entries };
      }
      const content = readFileSync(p, 'utf8');
      return { summary: `${path}: ${content.split('\n').length} lines.`, content: content.slice(0, 50_000) };
    });

  tool(server, ctx, 'memory_write', 'Create or replace a brain file (git-committed).',
    { path: z.string(), content: z.string() },
    async ({ path, content }) => {
      const p = brainPath(path, dir);
      if (existsSync(p) && statSync(p).isDirectory()) throw new UserError(`${path} is a folder.`);
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, content);
      await commit(dir, `memory_write: ${relative(dir, p)}`);
      return { summary: `Saved ${relative(dir, p)}.` };
    });

  tool(server, ctx, 'memory_append', 'Append text to a brain file, creating it if needed (git-committed).',
    { path: z.string(), text: z.string().min(1) },
    async ({ path, text }) => {
      const p = brainPath(path, dir);
      mkdirSync(dirname(p), { recursive: true });
      const sepNl = existsSync(p) && !readFileSync(p, 'utf8').endsWith('\n') ? '\n' : '';
      appendFileSync(p, `${sepNl}${text}\n`);
      await commit(dir, `memory_append: ${relative(dir, p)}`);
      return { summary: `Added to ${relative(dir, p)}.` };
    });

  tool(server, ctx, 'memory_delete', 'Delete a brain file or folder. Needs confirm=true. Recoverable from git history.',
    { path: z.string(), confirm: z.boolean().optional() },
    async ({ path, confirm }) => {
      const p = brainPath(path, dir);
      if (p === dir) throw new UserError('Refusing to delete the whole brain.');
      if (!existsSync(p)) throw new UserError(`${path} does not exist in the brain.`);
      if (confirm !== true) throw new UserError(`Deleting ${path} needs confirm=true. Ask the user first.`);
      await git(dir, 'rm', '-rq', '--', relative(dir, p)).catch(async () => {
        const { rmSync } = await import('node:fs'); rmSync(p, { recursive: true }); // untracked file
      });
      await commit(dir, `memory_delete: ${relative(dir, p)}`);
      return { summary: `Deleted ${relative(dir, p)}; it is still in git history.` };
    });

  tool(server, ctx, 'memory_link', 'Link a project to a shared brain file or folder (e.g. shared/deployment/expo) so it lands in the project\'s session context.',
    { project: z.string(), shared_path: z.string() },
    async ({ project, shared_path }) => {
      const p = findProject(ctx.cfg, project);
      const target = relative(dir, brainPath(shared_path, dir));
      if (!existsSync(join(dir, target))) throw new UserError(`${target} does not exist in the brain.`);
      if (links(ctx, p.id, dir).includes(target)) return { summary: `${p.id} is already linked to ${target}.` };
      const f = join(dir, 'projects', p.id, 'links.md');
      mkdirSync(dirname(f), { recursive: true });
      if (!existsSync(f)) writeFileSync(f, `# Shared knowledge linked to ${p.id}\n\n`);
      appendFileSync(f, `- ${target}\n`);
      await commit(dir, `memory_link: ${p.id} -> ${target}`);
      return { summary: `Linked ${p.id} to ${target}.` };
    });

  tool(server, ctx, 'project_context', 'Everything a session on this project should know: its notes, linked shared files and related skills, in one package.',
    { project: z.string() },
    async ({ project }) => {
      const c = projectContext(ctx, project, dir);
      return {
        summary: `${findProject(ctx.cfg, project).id}: ${c.notes.length} notes, ${c.shared.length} shared files, ${c.related_skills.length} related skills.`,
        ...c,
      };
    });
}
